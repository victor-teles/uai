/**
 * Writes the two indexes that used to be hand-maintained lists, so a new item only
 * adds its own files (CONTRIBUTING.md › Shared files):
 *
 * - `registry.json`, the shadcn source manifest, from one `<id>.json` per item next
 *   to its source in `src/registry/uai`.
 * - `src/components/registry/preview-entries.generated.ts`, the site's preview map,
 *   from one `<id>-entry.tsx` per item next to its `<id>-preview.tsx`.
 *
 * Both outputs are git-ignored. `registry:build`, `registry:check`, `typecheck`, and
 * `dev` run this first.
 */
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..");
const ITEMS_GLOB = "src/registry/uai/**/*.json";
const ENTRIES_DIR = "src/components/registry";
const ENTRIES_GLOB = "*/*-entry.tsx";
export const PREVIEW_ENTRIES_FILE = `${ENTRIES_DIR}/preview-entries.generated.ts`;

type RegistryItem = { name: string; type: string; [key: string]: unknown };

/** The theme first, then the shared libs, then every item by name. */
const typeRank = (item: RegistryItem) =>
  item.type === "registry:theme" ? 0 : item.type === "registry:lib" ? 1 : 2;

const scan = (pattern: string, cwd: string) =>
  [...new Bun.Glob(pattern).scanSync({ cwd })].sort((a, b) => a.localeCompare(b));

export async function readRegistryItems(): Promise<RegistryItem[]> {
  const items = await Promise.all(
    scan(ITEMS_GLOB, ROOT).map(async (file) => {
      const item = (await Bun.file(path.join(ROOT, file)).json()) as RegistryItem;
      if (item.name !== path.basename(file, ".json")) {
        throw new Error(`${file}: "name" must match the file name`);
      }
      return item;
    }),
  );
  return items.sort((a, b) => typeRank(a) - typeRank(b) || a.name.localeCompare(b.name));
}

export async function writeRegistryIndex() {
  const registry = {
    $schema: "https://ui.shadcn.com/schema/registry.json",
    name: "uai",
    homepage: "https://uaiblocks.dev",
    items: await readRegistryItems(),
  };
  await Bun.write(path.join(ROOT, "registry.json"), `${JSON.stringify(registry, null, 2)}\n`);

  const entries = scan(ENTRIES_GLOB, path.join(ROOT, ENTRIES_DIR)).map((file, index) => ({
    id: path.basename(file, "-entry.tsx"),
    binding: `entry${index}`,
    specifier: `./${file.replace(/\.tsx$/, "")}`,
  }));
  const source = [
    "// Generated by scripts/registry-index.ts from */<id>-entry.tsx. Do not edit.",
    'import type { RegistryItemId } from "./catalog";',
    'import type { PreviewEntry } from "./preview-chrome";',
    ...entries.map(
      ({ binding, specifier }) => `import { entry as ${binding} } from "${specifier}";`,
    ),
    "",
    "export const previewEntries: Partial<Record<RegistryItemId, PreviewEntry>> = {",
    ...entries.map(({ id, binding }) => `  ${JSON.stringify(id)}: ${binding},`),
    "};",
    "",
  ].join("\n");
  await Bun.write(path.join(ROOT, PREVIEW_ENTRIES_FILE), source);

  return { items: registry.items.length, entries: entries.length };
}

if (import.meta.main) {
  const { items, entries } = await writeRegistryIndex();
  console.log(`Indexed ${items} registry items and ${entries} preview entries.`);
}
